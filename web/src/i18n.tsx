const dict = { en, ru };

export type Msg = keyof typeof en;

const Ctx = createContext<{ lang: Lang; setLang: (lang: Lang) => void } | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem("lang") === "ru" ? "ru" : "en"));
  const setLang = (next: Lang) => {
    localStorage.setItem("lang", next);
    setLangState(next);
  };
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("i18n");
  const t = (key: Msg, vars?: Record<string, string | number>) => {
    const text = dict[ctx.lang][key];
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
  };
  return { lang: ctx.lang, setLang: ctx.setLang, t };
}
